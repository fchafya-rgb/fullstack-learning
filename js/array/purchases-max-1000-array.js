/*
Задача 3: Дан массив покупок в магазине:

Пройдись циклом по всем покупкам и выведи номер позиции (индекс) и сумму — но только для тех покупок, которые больше
1000 рублей (то есть не все 7 покупок, а только те, что подходят под условие).
*/

let purchases = [1200, 450, 3200, 890, 50, 2100, 670];
i = 0;

while (i < purchases.length) {

if (purchases[i] > 1000) {
    console.log(`Покупка №${i + 1} ${purchases[i]}`)
}

    i++;
}
