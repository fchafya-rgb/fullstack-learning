/*
Интернет-магазин рассчитывает скидку на заказ. Правила магазина:
- При заказе от 300 рублей премиум-клиент получает скидку 20%.
- Если первое правило не сработало, клиент с промокодом получает скидку 10%, но только при заказе от 150 рублей.
- Если ни одно из этих правил не выполнено, скидка не предоставляется.
*/

let orderPrice = 250;
let isPremium = false;
let hasPromoCode = true;

if (orderPrice >= 300 && isPremium) {
    console.log("Скидка 20%")
} else if (orderPrice >= 150 && hasPromoCode) {
    console.log("Скидка 10%")
} else {
    console.log("Скидка не предоставляется")
}

