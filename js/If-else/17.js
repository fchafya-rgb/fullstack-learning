/*
Есть студент с баллом за экзамен (0-100).
1. Оценка (буква) — ТРЕБУЕТ if/else if/else (5 взаимоисключающих вариантов):
   - 90-100: "A"
   - 75-89: "B"
   - 60-74: "C"
   - 40-59: "D"
   - 0-39: "F"
*/
let gradeStudents = 67;
let grade;

if (gradeStudents >= 90 && gradeStudents <= 100) {
    grade = `A`;
} else if (gradeStudents >= 75 && gradeStudents <= 89) {
    grade = `B`;
} else if (gradeStudents >= 60 && gradeStudents <= 74) {
    grade = `C`;
} else if (gradeStudents >= 40 && gradeStudents <= 59) {
    grade = `D`;
} else {
    grade = `F`;
}

/*
2. Статус сдачи — используй тернарный оператор:
   - балл >= 40 → "Сдал"
   - балл < 40 → "Не сдал"
*/
let yN = gradeStudents >= 40 ? "Сдал" : "Не сдал";


/*
3. Стипендия — используй тернарный оператор:
   - если оценка "A" (по буквенной оценке из пункта 1) → "Претендует на стипендию"
   - иначе → "Не претендует"
*/
let payDay = grade === "A" ? "Претендует на степендию" : "Не претендует";

/*
4. Пересдача — независимый фактор, НЕ связан с баллом напрямую, отдельный if/else:
   - если есть прогулы (переменная hasAbsences) И балл меньше 60 → "Требуется пересдача с разрешения деканата"
   - если есть прогулы, но балл 60+ → "Пересдача не требуется, но посещаемость под вопросом"
   - если прогулов нет → "Пересдача не требуется"
   (подумай — тут понадобится вложенность или комбинация условий с &&)
*/
let hasAbsences = false;
let last;
if (hasAbsences && gradeStudents < 60 ) {
    last = "Требуется пересдача с разрешения деканата";
} else if (hasAbsences && gradeStudents >= 60) {
    last = "Пересдача не требуется, но посещаемость под вопросом";
} else {
    last = "Пересдача не требуется";
}


/*
5. Итоговый отчёт:
Выведи ОДНИМ console.log через шаблонную строку: балл, буквенную оценку, статус сдачи,
информацию про стипендию, статус пересдачи.

Исходные данные задай сам (например: балл = 92, hasAbsences = true).
*/
console.log(`Балл: ${gradeStudents}
Буквенная оценка: ${grade}
Статус сдачи: ${yN}
Информация про степендию: ${payDay}
Статус пересдачи: ${last}`);

