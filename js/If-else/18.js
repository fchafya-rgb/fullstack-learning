/*
Есть заказ в сервисе доставки еды.

1. Стоимость доставки по расстоянию — ТРЕБУЕТ if/else if/else (взаимоисключающие варианты):
   - до 2 км включительно: 99 руб
   - от 2 до 5 км включительно: 149 руб
   - от 5 до 10 км включительно: 199 руб
   - больше 10 км: 299 руб
*/
let priceDelivery = 3;
let sumDelivery;
let sumCheck = 1200;

if (priceDelivery <= 2 ) {
    sumDelivery = 99;
} else if ( priceDelivery > 2 && priceDelivery <= 5) {
    sumDelivery = 149;
} else if (priceDelivery > 5 && priceDelivery <= 10) {
    sumDelivery = 199;
} else {
    sumDelivery = 299;
}


/*
2. Бесплатная доставка — используй тернарный оператор:
   - если сумма заказа >= 1500 руб → доставка становится 0 (независимо от расстояния)
   - иначе → остаётся стоимость из пункта 1
*/

let freeDelivery = sumCheck >= 1500 ? 0 : sumDelivery;

/*
3. Статус заказа — используй тернарный оператор:
   - если сумма заказа >= 300 → "Заказ принят"
   - иначе → "Минимальная сумма заказа 300 руб"
*/

let status = sumCheck >= 300 ? "Заказ принят" : "Минимальная сумма заказа 300 руб";

/*
4. Скидка новым клиентам — независимый фактор, отдельный if/else с комбинацией условий:
   - если клиент новый (isNewClient) И сумма заказа >= 500 → скидка 10% от суммы заказа
   - если клиент новый, но сумма заказа < 500 → скидка не применяется (нужна большая сумма)
   - если клиент не новый → скидка не применяется
*/
let isNewClient = true;
let skidkaNewUsers;
let discount;

if (isNewClient && sumCheck >= 500) {
    skidkaNewUsers = sumCheck * 10 / 100;
    discount = "Скидка применена";
} else if ( isNewClient && sumCheck < 500) {
    skidkaNewUsers = 0;
    discount = "Скидка не применяется ( нужна большая сумма";
} else {
    skidkaNewUsers = 0;
    discount = "Скидка не применяется";
}


/*
5. Итоговая сумма к оплате:
   сумма заказа (с учётом скидки, если она есть) + стоимость доставки (с учётом пункта 2)
*/
let total = sumCheck - skidkaNewUsers + freeDelivery;
/*
6. Оценка времени ожидания — if/else if/else по расстоянию (используй то же расстояние из пункта 1):
   - до 2 км: "15-20 минут"
   - от 2 до 5 км: "25-35 минут"
   - от 5 до 10 км: "40-55 минут"
   - больше 10 км: "60+ минут"
*/
let timeDelivery;

if (priceDelivery < 2) {
    timeDelivery = "15-20 минут";
} else if (priceDelivery >= 2 && priceDelivery < 5 ){
    timeDelivery = "25-35 минут";
} else if (priceDelivery >= 5 && priceDelivery < 10) {
    timeDelivery = "40-55 минут";
} else {
    timeDelivery = "60+ минут";
}

/*
7. Итоговый отчёт:
Выведи ОДНИМ console.log через шаблонную строку: сумму заказа, расстояние, стоимость доставки,
скидку (если есть), итоговую сумму, статус заказа, время ожидания.

Исходные данные задай сам (например: сумма заказа = 1800, расстояние = 7 км, новый клиент = true).
*/

console.log(`Сумма заказа: ${sumCheck} руб.
Расстояние: ${priceDelivery} км.
Стоимость доставки: ${sumDelivery} руб.
Скидка:${discount}
Итоговая сумма: ${total} руб.
Статус заказа: ${status}
Время ожидания: ${timeDelivery}`);

