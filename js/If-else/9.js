/*
Интернет-магазин рассчитывает стоимость доставки по следующим бизнес-правилам:
1. Экспресс-доставка всегда стоит 15 рублей — независимо от суммы заказа и статуса клиента.
2. Если выбрана обычная доставка и сумма заказа составляет 200 рублей или больше, доставка бесплатная.
3. Если выбрана обычная доставка, заказ меньше 200 рублей, но клиент премиум, доставка стоит 5 рублей.
4. Во всех остальных случаях обычная доставка стоит 10 рублей.
*/

let orderPrice = 120;
let isPremium = true;
let isExpress = false;

if (isExpress) {
    console.log("Доставка стоит 15 рубелй")
} else if (orderPrice >= 200) {
    console.log("Доставка бесплатная")
} else if (isPremium) {
    console.log("Доставка стоит 5 рублей")
} else {
    console.log("Доставка стоит 10 рублей")
}

