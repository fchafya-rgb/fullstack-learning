/* Требования:
1. Если сумма заказа составляет не менее 300 и клиент является премиум-клиентом, вывести Скидка 20%.
2. Если первое условие не выполнено, но у клиента есть промокод и сумма заказа составляет не менее 200, вывести Скидка 10%.
3. Если ни одно условие не выполнено, вывести Скидка не предоставляется.*/


let orderPrice = 350;
let isPremium = false;
let hasPromoCode = true;

if ( orderPrice >= 300 && isPremium) {
    console.log("Скидка 20%")
} else if ( hasPromoCode && orderPrice >= 200) {
    console.log("Скидка 10%")
} else {
    console.log("Скидка не предоставляется!")
}