/* Представь, что интернет-магазин предоставляет скидку по следующим правилам:
- Если заказ составляет 200 рублей или больше — скидка предоставляется.
- Если заказ меньше 200 рублей, но у покупателя есть промокод — скидка тоже предоставляется.
- Во всех остальных случаях скидки нет.
Твоя задача: написать условие, которое выводит:
- "Скидка предоставлена"
- "Скидки нет"
Дополнительные требования:
- Используй if и else.
- Не меняй значения переменных.
- Не используй else if. */

let orderPrice = 150;
let hasPromoCode = true;

if ( orderPrice >= 200 || hasPromoCode) {
    console.log("Скидка предоставляется")
} else {
    console.log("Скидки нет")
}