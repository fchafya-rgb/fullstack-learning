/*
1.Если сумма заказа не меньше 200, доставка бесплатная.
2.Если первое условие не выполнено, но клиент премиум, доставка стоит 5 рублей.
3.Если ни одно из предыдущих условий не выполнено, но клиент выбрал экспресс-доставку, стоимость доставки составляет 15 рублей.
4.Во всех остальных случаях стоимость доставки составляет 10 рублей.
*/


let orderPrice = 120;
let isPremium = true;
let isExpress = false;

if ( orderPrice >= 200) {
    console.log("Доставка бесплатная")
} else if (isPremium) {
    console.log("Стоимсоть доставки: 5 рублей")
} else if (isExpress) {
    console.log("Вы выбрали экспресс-доставку, стоимость 15 рублей")
} else {
    console.log("Стоимсоть доставки состовляет 10 рублей")
}

