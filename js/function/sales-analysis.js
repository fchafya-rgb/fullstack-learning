/*
Напиши функцию анализПродаж(выручкаЗаДень), которая принимает одно число и возвращает:

меньше 5000 → "Плохой день"
от 5000 до 15000 включительно → "Обычный день"
больше 15000 → "Отличный день"
*/
/*
Задача: Отдельно от функции (снаружи, после неё), с помощью while, сгенерируй и выведи в консоль анализ продаж для 5 разных дней подряд.

Требования:

Нужен счётчик дней, который начинается с 1 и доходит до 5 (цикл должен выполниться ровно 5 раз)
На каждом шаге цикла должна быть своя, отличающаяся от других, выручка за день (придумай любой способ получить
разные числа на каждом шаге — например, через математическое выражение, зависящее от счётчика)
На каждом шаге вызови функцию salesAnalysis(выручка) с этой выручкой
Выведи для каждого дня результат — например, что-то вроде "День 1: Отличный день" (номер дня + статус)
*/



function salesAnalysis(a) {

    if (a < 5000 ) {
        return `Плохой день`;
    } else if (a >= 5000 && a <= 15000){
        return `Обычный день`;
    } else {
        return `Отличный день`;
    }
}


let i = 0;

while (i < 5) {
i++;
let total = i * Math.random() * 12000;
console.log(`День ${i}: ${Math.trunc(total)} руб - ${salesAnalysis(total)}`);
}