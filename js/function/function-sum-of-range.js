/*
Напиши функцию суммаДиапазона(от, до), которая возвращает сумму всех чисел от от до до включительно, используя for внутри.

Пример: суммаДиапазона(1, 5) должна вернуть 15 (1+2+3+4+5).
*/


function sumRange(i,a){
    let b = 0;
    for (i; i <= a; i++){
        b = i + b;
    }
    return b;
}

let total = sumRange(0,5);
