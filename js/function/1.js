/*
Напиши функцию категорияБМИ(вес, рост), которая считает индекс массы тела (вес / (рост * рост), рост в метрах)
и возвращает одну из строк в зависимости от результата:

меньше 18.5 — "Недостаточный вес"
от 18.5 до 25 (включительно) — "Норма"
больше 25 — "Избыточный вес"
*/


function BMI(x,y){
    let z = x / (y * y);


    if (z < 18.5) {
        return "Недостаточный вес";
    } else if (z >= 18.5 && z <= 25) {
        return "Норма";
    } else {
        return "Избыточный вес";
    }
}


