/*
На складе есть запас товара и очередь заказов, которые нужно обработать по очереди,
пока либо не закончится товар на складе, либо не закончится очередь заказов.

Исходные данные:
всего единиц товара на складе - 500
количество заказов в очереди - 12
сколько единиц товара в одном заказе (одинаково для всех, для простоты) - 45
после скольки обработанных заказов включается "режим нехватки" - 3
*/
let totalItems = 500;
let totalOrderQueue = 12;
let oneQueueItems = 45;
let scarcityMod = 3;
let compliteQueue = 0;
/*
Логика обработки (один заказ = один проход цикла while):

1. Пока в очереди есть заказы И на складе хватает товара
   на текущий заказ — продолжай обрабатывать.

2. Для каждого обработанного заказа:
   - Спиши товар со склада
   - Уменьши очередь на один заказ
   - Увеличь счётчик обработанных заказов

   3. Внутри цикла, для каждого обработанного заказа, определи его статус (if/else):
   - Если после списания на складе осталось МЕНЬШЕ 100 единиц — статус "Внимание: товар заканчивается"
   - Если осталось от 100 до 250 (включительно) — статус "В норме"
   - Если осталось больше 250 — статус "Склад в достатке"

*/
let status = "";

while ( totalOrderQueue > 0 && totalItems >= oneQueueItems) {
    totalItems = totalItems- oneQueueItems;
    totalOrderQueue -= 1;
    compliteQueue++;

    if ( totalItems < 100 && compliteQueue >= scarcityMod ) {
        status = `Внимание: товар заканчивается, РЕЖИМ НЕХВАТКИ АКТИВИРОВАН`
    } else if (totalItems >= 100 && totalItems <= 250 ) {
        status = `В норме`
    } else {
        status = `Склад в достатке`
    }
}

