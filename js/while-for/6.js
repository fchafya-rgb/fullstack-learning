/*
Задача 4 (на while). Есть число password = 1234. Пользователь вводит попытки (просто задай массив-подобный список чисел
вручную, например через несколько переменных или просто представь, что угадываешь с N-й попытки) — хотя это чуть сложнее,
 пока пропусти если не знаешь массивы. Вместо этого сделай проще: с помощью while посчитай, сколько раз нужно удвоить число 1,
  чтобы оно превысило 1000 (то есть 1 → 2 → 4 → 8... пока не станет больше 1000), и выведи итоговое число и количество удвоений.
 */


let number = 1;
let count = 0;

while (number <= 1000){
    number *= 2;
    count++;

}
console.log(`Готовое число: ${number}
Кол-во удвоений: ${count}`);